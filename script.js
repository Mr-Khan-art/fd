/* =====================================================
   DATE FORMAT
===================================================== */

function formatDate(date) {

    const parts = date.split("-");

    const day = parts[0];

    return `${day} অক্টোবর ২০২৬`;
}


/* =====================================================
   MEAL ICON
===================================================== */

function mealIcon(meal) {

    if (meal === "সকাল") {
        return "🌅";
    }

    if (meal === "দুপুর") {
        return "☀️";
    }

    return "🌙";
}


/* =====================================================
   SEARCH DUTY BY ID
===================================================== */

function searchDuty() {

    const idInput =
        document.getElementById("idInput");

    const id =
        idInput.value.trim();

    const result =
        document.getElementById("result");


    if (id === "") {

        result.innerHTML = `
            <div class="error">
                ⚠️ অনুগ্রহ করে ID লিখুন।
            </div>
        `;

        return;
    }


    const found =
        duties.filter(item => item[3] === id);


    if (found.length === 0) {

        result.innerHTML = `
            <div class="error">

                ❌ <b>${id}</b> ID-এর
                কোনো দায়িত্ব পাওয়া যায়নি।

            </div>
        `;

        return;
    }


    const name =
        people[id] || "নাম পাওয়া যায়নি";


    let html = `

        <div class="result-card">

            <div class="result-title">

                <h2>আপনার দায়িত্ব</h2>

                <p>অক্টোবর ২০২৬</p>

            </div>


            <div class="person">

                <div class="person-name">
                    ${name}
                </div>

                <div class="person-id">
                    ID: ${id}
                </div>

            </div>

    `;


    found.forEach(item => {

        const date = item[0];

        const day = item[1];

        const meal = item[2];

        const shift = item[4];


        html += `

            <div class="duty-card">

                <div class="duty-date">

                    📅 ${formatDate(date)}

                </div>


                <div class="duty-day">

                    ${day}

                </div>


                <div class="tags">

                    <span class="tag">

                        ${mealIcon(meal)}
                        ${meal}

                    </span>

                    ${
                        shift
                        ?
                        `
                        <span class="tag shift-tag">

                            ⏱️ ${shift}

                        </span>
                        `
                        :
                        ""
                    }

                </div>

            </div>

        `;

    });


    html += `</div>`;


    result.innerHTML = html;


    result.scrollIntoView({
        behavior: "smooth"
    });
}


/* =====================================================
   TODAY'S DUTY
===================================================== */

function showTodayDuty() {

    const result =
        document.getElementById("result");


    const today =
        new Date();


    const day =
        String(today.getDate()).padStart(2, "0");


    const month =
        String(today.getMonth() + 1).padStart(2, "0");


    const year =
        today.getFullYear();


    const todayString =
        `${day}-${month}-${year}`;


    const found =
        duties.filter(
            item => item[0] === todayString
        );


    if (found.length === 0) {

        result.innerHTML = `

            <div class="error">

                📅 আজকের তারিখের জন্য
                কোনো দায়িত্ব পাওয়া যায়নি।

            </div>

        `;

        return;
    }


    let html = `

        <div class="result-card">

            <div class="result-title">

                <h2>📅 আজকের দায়িত্ব</h2>

                <p>
                    ${formatDate(todayString)}
                    •
                    ${found[0][1]}
                </p>

            </div>

    `;


    found.forEach(item => {

        const meal = item[2];

        const id = item[3];

        const shift = item[4];

        const name =
            people[id] || "নাম পাওয়া যায়নি";


        html += `

            <div class="duty-card">

                <div class="duty-date">

                    ${mealIcon(meal)}
                    ${meal}

                </div>


                <div class="duty-day">

                    <b>${name}</b>

                    <br>

                    ID: ${id}

                </div>


                ${
                    shift
                    ?
                    `
                    <div class="tags">

                        <span class="tag shift-tag">

                            ⏱️ ${shift}

                        </span>

                    </div>
                    `
                    :
                    ""
                }

            </div>

        `;

    });


    html += `</div>`;


    result.innerHTML = html;


    result.scrollIntoView({
        behavior: "smooth"
    });
}
